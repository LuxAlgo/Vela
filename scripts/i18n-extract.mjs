// Extracts every `msg('id', 'English text')` call in src/ into the English catalog:
//  - src/locales/en.json   — id → English message, the source every translation starts from;
//  - src/locales/catalog.d.ts — the ids as a type, which fills `VelaMessageCatalog`.
//
//   node scripts/i18n-extract.mjs          write both files
//   node scripts/i18n-extract.mjs --check  fail when either file is out of date
//
// Both arguments of `msg()` must be string literals; anything else is reported. Both modes
// then list how many messages each pack under src/locales/ translates. That line is
// information only: a message a pack lacks reads in English.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ID_PATTERN = /^[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9]+)+$/;

/** The repository root, as a native path. */
export const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));

function sourceFiles(dir) {
    const out = [];
    for (const name of readdirSync(dir)) {
        const full = join(dir, name);
        if (statSync(full).isDirectory()) out.push(...sourceFiles(full));
        else if (name.endsWith('.ts') && !name.endsWith('.d.ts') && !name.endsWith('.test.ts')) out.push(full);
    }
    return out.sort();
}

const literalText = (node) => (node && (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) ? node.text : null);

/** Every `msg()` call under `root/src` and the kit's `packages/vela-ui/src` (its own words
 *  translate with Vela's): `{ messages: Map<id, text>, errors: string[] }`. */
export function collectMessages(root) {
    const messages = new Map();
    const where = new Map();
    const errors = [];
    const files = [...sourceFiles(join(root, 'src')), ...sourceFiles(join(root, 'packages/vela-ui/src'))];
    for (const file of files) {
        const text = readFileSync(file, 'utf8');
        if (!text.includes('msg(')) continue;
        const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
        const rel = relative(root, file).split(sep).join('/');
        const visit = (node) => {
            if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'msg') {
                const { line } = sf.getLineAndCharacterOfPosition(node.getStart(sf));
                const at = `${rel}:${line + 1}`;
                const id = literalText(node.arguments[0]);
                const message = literalText(node.arguments[1]);
                if (id === null || message === null || node.arguments.length !== 2) {
                    errors.push(`${at}: msg() needs two string literals (an id and its English text)`);
                } else if (!ID_PATTERN.test(id)) {
                    errors.push(`${at}: message id "${id}" must be dotted camelCase segments, e.g. "widget.shortcuts.title"`);
                } else if (messages.has(id) && messages.get(id) !== message) {
                    errors.push(`${at}: message id "${id}" already has different English text at ${where.get(id)}`);
                } else if (!messages.has(id)) {
                    messages.set(id, message);
                    where.set(id, at);
                }
            }
            ts.forEachChild(node, visit);
        };
        visit(sf);
    }
    return { messages, errors };
}

const sortedIds = (messages) => [...messages.keys()].sort();

/** The English catalog file. */
export function renderEnJson(messages) {
    const obj = {};
    for (const id of sortedIds(messages)) obj[id] = messages.get(id);
    return `${JSON.stringify(obj, null, 4)}\n`;
}

/** The generated type that fills `VelaMessageCatalog`. */
export function renderCatalog(messages) {
    const rows = sortedIds(messages).map((id) => `    ${JSON.stringify(id).replace(/^"|"$/g, "'")}: string;`);
    return [
        '// Generated by `npm run i18n:extract` from every msg() call in src/. Do not edit:',
        '// change the msg() call and run the script again.',
        '',
        '/** Every message id of the core, as a key. */',
        'export interface VelaCoreMessageCatalog {',
        ...rows,
        '}',
        '',
    ].join('\n');
}

/** The two generated files, keyed by path relative to the root. */
export function generatedFiles(root) {
    const { messages, errors } = collectMessages(root);
    return {
        errors,
        files: {
            'src/locales/en.json': renderEnJson(messages),
            'src/locales/catalog.d.ts': renderCatalog(messages),
        },
    };
}

/** Extraction errors, and the generated files whose content on disk is out of date. */
export function checkGenerated(root) {
    const { errors, files } = generatedFiles(root);
    const stale = [];
    for (const [rel, content] of Object.entries(files)) {
        let current = null;
        try {
            // A checkout with `core.autocrlf` holds CRLF; the generated content is LF.
            current = readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n');
        } catch {
            current = null;
        }
        if (current !== content) stale.push(rel);
    }
    return { errors, stale, files };
}

/** How much of the English catalog each shipped pack translates: `[{ tag, translated, total }]`.
 *  Information only: a message a pack lacks reads in English. */
export function packCoverage(root) {
    const dir = join(root, 'src/locales');
    const english = JSON.parse(readFileSync(join(dir, 'en.json'), 'utf8'));
    const total = Object.keys(english).length;
    return readdirSync(dir)
        .filter((name) => name.endsWith('.json') && name !== 'en.json')
        .sort()
        .map((name) => {
            const pack = JSON.parse(readFileSync(join(dir, name), 'utf8'));
            const translated = Object.keys(pack).filter((id) => id in english).length;
            return { tag: name.slice(0, -'.json'.length), translated, total };
        });
}

function printCoverage(root) {
    const rows = packCoverage(root);
    if (!rows.length) return;
    console.log('Locale packs (messages translated / English messages):');
    const width = Math.max(...rows.map((r) => r.tag.length));
    for (const { tag, translated, total } of rows) console.log(`  ${tag.padEnd(width)}  ${translated} / ${total}${translated < total ? `  (${total - translated} read in English)` : ''}`);
}

function main() {
    const { errors, stale, files } = checkGenerated(repoRoot);
    if (errors.length) {
        for (const e of errors) console.error(e);
        process.exit(1);
    }
    if (process.argv.includes('--check')) {
        for (const rel of stale) console.error(`${rel} is out of date: run \`npm run i18n:extract\`.`);
        if (stale.length) process.exit(1);
        printCoverage(repoRoot);
        return;
    }
    for (const rel of stale) {
        writeFileSync(join(repoRoot, rel), files[rel]);
        console.log(`wrote ${rel}`);
    }
    printCoverage(repoRoot);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
